        SELECT 1 FROM workout_sets s
        JOIN workout_session_plans wsp ON wsp.workout_session_id = s.workout_session_id
        WHERE NOT EXISTS (
            SELECT 1 FROM plan_exercises pe
            WHERE pe.plan_day_id = wsp.plan_day_id AND pe.exercise_id = s.exercise_id
        )
    ) THEN
        RAISE EXCEPTION 'workout_sets contains an exercise outside its source plan day';
    END IF;
    IF EXISTS (
        SELECT 1 FROM workout_plans wp
        JOIN users u ON u.user_id = wp.user_id
        WHERE u.age IS NULL OR u.height_cm IS NULL
           OR NOT EXISTS (SELECT 1 FROM body_records br WHERE br.user_id = u.user_id)
    ) THEN
        RAISE EXCEPTION 'a legacy workout plan owner lacks age, height, or a weight record required for snapshot backfill';
    END IF;
END;
$$;

