    UNIQUE (user_id, priority)
);

CREATE TABLE body_records (
    body_record_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE ON UPDATE RESTRICT,
    record_date DATE NOT NULL CHECK (record_date <= CURRENT_DATE),
    weight_kg NUMERIC(6,2) NOT NULL CHECK (weight_kg BETWEEN 20.00 AND 500.00),
