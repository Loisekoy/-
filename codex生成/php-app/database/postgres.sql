CREATE OR REPLACE FUNCTION reject_exercise_version_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'exercise_versions are immutable; create a new version instead' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER trg_exercise_versions_immutable
    BEFORE UPDATE OR DELETE ON exercise_versions
    FOR EACH ROW EXECUTE FUNCTION reject_exercise_version_mutation();

CREATE OR REPLACE FUNCTION validate_plan_exercise_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM plan_exercises other
        JOIN exercise_versions ov ON ov.exercise_version_id = other.exercise_version_id
        JOIN exercise_versions nv ON nv.exercise_version_id = NEW.exercise_version_id
        WHERE other.plan_day_id = NEW.plan_day_id
          AND other.plan_exercise_id <> COALESCE(NEW.plan_exercise_id, 0)
          AND ov.exercise_id = nv.exercise_id
    ) THEN
        RAISE EXCEPTION 'the same exercise identity cannot appear twice on one plan day' USING ERRCODE = '23505';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_plan_exercise_identity_unique
    BEFORE INSERT OR UPDATE OF plan_day_id, exercise_version_id ON plan_exercises
    FOR EACH ROW EXECUTE FUNCTION validate_plan_exercise_identity();

CREATE OR REPLACE FUNCTION validate_session_exercise_snapshot() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    source_day INTEGER;
    item_day INTEGER;
    item_version INTEGER;
BEGIN
    SELECT plan_day_id INTO source_day FROM workout_session_plans
    WHERE workout_session_id = NEW.workout_session_id;
    SELECT plan_day_id, exercise_version_id INTO item_day, item_version FROM plan_exercises
    WHERE plan_exercise_id = NEW.plan_exercise_id;
    IF source_day IS NULL OR item_day IS NULL OR source_day <> item_day THEN
        RAISE EXCEPTION 'session exercise does not belong to the session source plan day' USING ERRCODE = '23503';
    END IF;
    IF item_version <> NEW.exercise_version_id THEN
        RAISE EXCEPTION 'session exercise version must match its source plan exercise' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_session_exercise_snapshot_guard
    BEFORE INSERT OR UPDATE OF workout_session_id, plan_exercise_id, exercise_version_id
    ON workout_session_exercises
    FOR EACH ROW EXECUTE FUNCTION validate_session_exercise_snapshot();

CREATE OR REPLACE FUNCTION lock_and_protect_last_body_record() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    completed TIMESTAMPTZ;
    remaining INTEGER;
BEGIN
    PERFORM pg_advisory_xact_lock(8021, OLD.user_id);
    SELECT profile_completed_at INTO completed FROM users WHERE user_id = OLD.user_id;
    IF NOT FOUND THEN RETURN OLD; END IF;
    IF completed IS NOT NULL THEN
        SELECT COUNT(*) INTO remaining FROM body_records
        WHERE user_id = OLD.user_id AND body_record_id <> OLD.body_record_id;
        IF remaining < 1 THEN
            RAISE EXCEPTION 'a completed profile must retain at least one body record' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN OLD;
END;
$$;
CREATE TRIGGER trg_body_records_keep_last
    BEFORE DELETE ON body_records
    FOR EACH ROW EXECUTE FUNCTION lock_and_protect_last_body_record();

CREATE OR REPLACE FUNCTION ensure_completed_session_has_set() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    target_session INTEGER;
    target_status VARCHAR(20);
BEGIN
    IF TG_TABLE_NAME = 'workout_sessions' THEN
        target_session := COALESCE(NEW.workout_session_id, OLD.workout_session_id);
        target_status := COALESCE(NEW.status, OLD.status);
    ELSIF TG_TABLE_NAME = 'workout_session_exercises' THEN
        target_session := COALESCE(NEW.workout_session_id, OLD.workout_session_id);
        SELECT status INTO target_status FROM workout_sessions
        WHERE workout_session_id = target_session FOR UPDATE;
    ELSE
        SELECT workout_session_id INTO target_session FROM workout_session_exercises
        WHERE workout_session_exercise_id = COALESCE(NEW.workout_session_exercise_id, OLD.workout_session_exercise_id);
        SELECT status INTO target_status FROM workout_sessions
        WHERE workout_session_id = target_session FOR UPDATE;
    END IF;
    IF target_status = 'completed' AND NOT EXISTS (
        SELECT 1 FROM workout_sets ws
        JOIN workout_session_exercises wse ON wse.workout_session_exercise_id = ws.workout_session_exercise_id
        WHERE wse.workout_session_id = target_session
    ) THEN
        RAISE EXCEPTION 'a completed workout session must contain at least one set' USING ERRCODE = '23514';
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$;
CREATE CONSTRAINT TRIGGER trg_completed_session_has_set
    AFTER INSERT OR UPDATE OF status ON workout_sessions
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION ensure_completed_session_has_set();
CREATE CONSTRAINT TRIGGER trg_completed_session_set_delete
    AFTER DELETE OR UPDATE OF workout_session_exercise_id ON workout_sets
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION ensure_completed_session_has_set();
CREATE CONSTRAINT TRIGGER trg_completed_session_exercise_delete
    AFTER DELETE OR UPDATE OF workout_session_id ON workout_session_exercises
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION ensure_completed_session_has_set();

CREATE OR REPLACE FUNCTION prevent_active_plan_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    affected_plan INTEGER;
BEGIN
    IF TG_TABLE_NAME = 'workout_plans' THEN
        affected_plan := OLD.workout_plan_id;
    ELSIF TG_TABLE_NAME = 'plan_days' THEN
        affected_plan := OLD.workout_plan_id;
    ELSE
        SELECT workout_plan_id INTO affected_plan FROM plan_days WHERE plan_day_id = OLD.plan_day_id;
    END IF;
    IF EXISTS (
        SELECT 1 FROM workout_sessions ws
        JOIN workout_session_plans wsp ON wsp.workout_session_id = ws.workout_session_id
        JOIN plan_days pd ON pd.plan_day_id = wsp.plan_day_id
        WHERE pd.workout_plan_id = affected_plan AND ws.status = 'in_progress'
    ) THEN
        RAISE EXCEPTION 'source plan is locked while a workout is in progress' USING ERRCODE = '55006';
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$;
CREATE TRIGGER trg_lock_active_workout_plan BEFORE UPDATE OR DELETE ON workout_plans
    FOR EACH ROW EXECUTE FUNCTION prevent_active_plan_mutation();
CREATE TRIGGER trg_lock_active_plan_day BEFORE UPDATE OR DELETE ON plan_days
    FOR EACH ROW EXECUTE FUNCTION prevent_active_plan_mutation();
CREATE TRIGGER trg_lock_active_plan_exercise BEFORE UPDATE OR DELETE ON plan_exercises
    FOR EACH ROW EXECUTE FUNCTION prevent_active_plan_mutation();

